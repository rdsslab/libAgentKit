export const getTranslator = (language = "en") => {
	const lang = MESSAGES[language] ? language : "en";
	const dict = MESSAGES[lang];
	const fallback = MESSAGES.en;
	return (key) => (dict && key in dict ? dict[key] : (fallback[key] ?? key));
};

